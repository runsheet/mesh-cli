const meshMarketplaceName = "mesh"

type pluginManifest struct {
	Name        string   `json:"name"`
	Description string   `json:"description"`
	Version     string   `json:"version"`
	Keywords    []string `json:"keywords,omitempty"`
}

type marketplaceManifest struct {
	Schema      string                 `json:"$schema,omitempty"`
	Name        string                 `json:"name"`
	Description string                 `json:"description"`
	Owner       map[string]string      `json:"owner,omitempty"`
	Plugins     []marketplacePluginRef `json:"plugins"`
}

type marketplacePluginRef struct {
	Name        string `json:"name"`
	Description string `json:"description,omitempty"`
	Source      string `json:"source"`
	Category    string `json:"category,omitempty"`
}

func atomicWriteFile(path string, data []byte, perm os.FileMode) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, perm); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

func meshMarketplaceDir() (string, error) {
	dir, err := paths.MeshDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(dir, "marketplace"), nil
}

func agentPluginDir(agentName string) (string, error) {
	dir, err := paths.AgentWorkdir(agentName)
	if err != nil {
		return "", err
	}
	return filepath.Join(dir, "plugin"), nil
}

func writeAgentPluginManifest(agentName string, ch []channels.Spec) error {
	pdir, err := agentPluginDir(agentName)
	if err != nil {
		return err
	}
	manifestDir := filepath.Join(pdir, ".claude-plugin")
	if err := os.MkdirAll(manifestDir, 0o700); err != nil {
		return err
	}
	manifest := pluginManifest{
		Name:        agentName,
		Description: agentPluginDescription(agentName, ch),
		Version:     "0.1.0",
		Keywords:    []string{"mesh", "channel"},
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	return atomicWriteFile(filepath.Join(manifestDir, "plugin.json"), data, 0o600)
}

func agentPluginDescription(agentName string, ch []channels.Spec) string {
	types := map[string]bool{}
	for _, c := range ch {
		types[c.Type] = true
	}
	if len(types) == 0 {
		return fmt.Sprintf("Mesh agent %q (no channels configured)", agentName)
	}
	tlist := make([]string, 0, len(types))
	for t := range types {
		tlist = append(tlist, t)
	}
	sort.Strings(tlist)
	return fmt.Sprintf("Mesh agent %q — channels: %s", agentName, strings.Join(tlist, ", "))
}

func syncMeshMarketplace() error {
	mkDir, err := meshMarketplaceDir()
	if err != nil {
		return err
	}
	pluginDir := filepath.Join(mkDir, ".claude-plugin")
	if err := os.MkdirAll(pluginDir, 0o700); err != nil {
		return err
	}

	agents, err := state.ListAgents()
	if err != nil {
		return fmt.Errorf("list agents: %w", err)
	}

	homeDir, err := os.UserHomeDir()
	if err != nil {
		return err
	}

	plugins := make([]marketplacePluginRef, 0, len(agents))
	for _, a := range agents {
		if len(a.Channels) == 0 {
			continue
		}
		pluginPath := filepath.Join(homeDir, ".mesh", "agents", a.Name, "plugin")
		rel, err := filepath.Rel(mkDir, pluginPath)
		if err != nil {
			rel = pluginPath
		}
		plugins = append(plugins, marketplacePluginRef{
			Name:        a.Name,
			Description: agentPluginDescription(a.Name, a.Channels),
			Source:      "./" + rel,
			Category:    "mesh",
		})
	}
	sort.Slice(plugins, func(i, j int) bool { return plugins[i].Name < plugins[j].Name })

	manifest := marketplaceManifest{
		Schema:      "https://anthropic.com/claude-code/marketplace.schema.json",
		Name:        meshMarketplaceName,
		Description: "Locally-managed marketplace generated by the mesh CLI. One plugin per registered mesh agent that has channels.",
		Owner: map[string]string{
			"name": "mesh",
		},
		Plugins: plugins,
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	return atomicWriteFile(filepath.Join(pluginDir, "marketplace.json"), data, 0o600)
}

// writeClaudeSettingsForDaemon is the WriteSettings callback passed to RunDaemon.
func writeClaudeSettingsForDaemon(agentName string, ch []channels.Spec, envSource map[string]string) error {
	dir, err := paths.AgentWorkdir(agentName)
	if err != nil {
		return err
	}
	pluginDir := filepath.Join(dir, "plugin")
	pluginManifestDir := filepath.Join(pluginDir, ".claude-plugin")
	if err := os.MkdirAll(pluginManifestDir, 0o700); err != nil {
		return fmt.Errorf("create plugin dir: %w", err)
	}
	_ = os.Remove(filepath.Join(dir, ".mcp.json"))
	_ = os.RemoveAll(filepath.Join(dir, ".claude-plugin"))

	exe, err := os.Executable()
	if err != nil {
		return fmt.Errorf("resolve mesh binary path: %w", err)
	}

	settings := claudeconf.Settings{
		MCPServers: map[string]claudeconf.MCPServerEntry{
			"mesh": {
				Command: exe,
				Args:    []string{"channel-server", "mesh-shim", "--agent", agentName},
			},
		},
	}

	data, err := json.MarshalIndent(settings, "", "  ")
	if err != nil {
		return err
	}
	mcpPath := filepath.Join(pluginDir, ".mcp.json")
	if err := os.WriteFile(mcpPath, data, 0o600); err != nil {
		return err
	}

	if len(ch) > 0 {
		if err := writeAgentPluginManifest(agentName, ch); err != nil {
			return fmt.Errorf("write plugin manifest: %w", err)
		}
	}
	if err := syncMeshMarketplace(); err != nil {
		fmt.Printf("mesh: marketplace sync failed: %v\n", err)
	}
	return nil
}

package mcpinstall

import (
	"fmt"
	"strings"
)

// Rendered is one instruction file rendered from the skill for one
// client. Marked says it is a section spliced into a file the person
// owns with UpsertMarked, rather than written whole.
type Rendered struct {
	Path   string
	Body   []byte
	Marked bool
}

// frontmatter is the skill's own name and description (SKILL.md's
// shape, and Cursor's user skill, which is the same shape, ADR-025).
type frontmatter struct {
	Name        string
	Description string
}

// parseSkill splits skill into its frontmatter and body: the text
// after the closing `---`, its leading blank lines trimmed.
func parseSkill(skill []byte) (frontmatter, string, error) {
	s := string(skill)
	if !strings.HasPrefix(s, "---\n") {
		return frontmatter{}, "", fmt.Errorf("mcpinstall: render: skill has no frontmatter")
	}
	rest := s[len("---\n"):]
	end := strings.Index(rest, "\n---")
	if end == -1 {
		return frontmatter{}, "", fmt.Errorf("mcpinstall: render: skill frontmatter has no closing ---")
	}
	head, body := rest[:end], rest[end+len("\n---"):]
	body = strings.TrimLeft(body, "\n")

	var fm frontmatter
	for _, line := range strings.Split(head, "\n") {
		if v, ok := strings.CutPrefix(line, "name:"); ok {
			fm.Name = strings.TrimSpace(v)
		}
		if v, ok := strings.CutPrefix(line, "description:"); ok {
			fm.Description = strings.TrimSpace(v)
		}
	}
	return fm, body, nil
}

// substitution is one body text replacement a client's render makes,
// so the client-specific lines — the add command, "from Claude Code",
// the `/mesh` form names — are never a second copy of the text
// (ADR-025's amendment, item 3).
type substitution struct{ old, new string }

func substitute(s string, subs []substitution) string {
	for _, sub := range subs {
		s = strings.ReplaceAll(s, sub.old, sub.new)
	}
	return s
}

// codexForms are SKILL.md's form headings, each `## \`/mesh <name>
// <hint>\`` turned into `## \`/prompts:mesh <name> $ARGUMENTS\`` —
// Codex's prompts take one $ARGUMENTS blob, documented at
// learn.chatgpt.com/docs/custom-prompts (fetched 2026-10-05) — or with
// no hint, `## \`/prompts:mesh <name>\``.
var codexForms = []string{"goals", "join", "switch", "status", "finish"}

func codexSubstitutions(body string) []substitution {
	subs := []substitution{
		{"from Claude Code", "from Codex"},
		{"claude mcp add mesh -- mesh mcp", "mesh mcp install --client codex"},
	}
	for _, form := range codexForms {
		old := findHeading(body, form)
		if old == "" {
			continue
		}
		new := "## `/prompts:mesh " + form + "`"
		if strings.ContainsAny(old, "<[") {
			new = "## `/prompts:mesh " + form + " $ARGUMENTS`"
		}
		subs = append(subs, substitution{old, new})
	}
	return subs
}

func cursorSubstitutions() []substitution {
	return []substitution{
		{"from Claude Code", "from Cursor"},
		{"claude mcp add mesh -- mesh mcp", "mesh mcp install --client cursor"},
	}
}

// findHeading is SKILL.md's `## ` line for /mesh form, else "".
func findHeading(body, form string) string {
	prefix := "## `/mesh " + form
	for _, line := range strings.Split(body, "\n") {
		if strings.HasPrefix(line, prefix) {
			return line
		}
	}
	return ""
}

// codexComment is the leading comment Codex's prompt file carries,
// naming it generated so a person does not hand-edit it.
const codexComment = "<!-- generated by `mesh mcp install`; edits are overwritten on the next run -->\n\n"

// Render is the skill's instructions for one client — claude, codex or
// cursor — each file rendered from the skill's own frontmatter and
// body (ADR-025's amendment, item 3): Claude's skill whole, unchanged;
// Codex's prompt (the body, commented, `/mesh`'s form headings turned
// into `/prompts:mesh … $ARGUMENTS`) and its AGENTS.md section (the
// same body, Marked for UpsertMarked); Cursor's user skill (the same
// frontmatter and a body of its own) and command (the body alone) —
// the client-specific lines substituted, never a second copy of the
// text.
func Render(client string, skill []byte) ([]Rendered, error) {
	fm, body, err := parseSkill(skill)
	if err != nil {
		return nil, err
	}
	switch client {
	case "claude":
		return []Rendered{{Path: "skills/mesh/SKILL.md", Body: skill}}, nil
	case "codex":
		b := substitute(body, codexSubstitutions(body))
		return []Rendered{
			{Path: "prompts/mesh.md", Body: []byte(codexComment + b)},
			{Path: "AGENTS.md", Body: []byte(b), Marked: true},
		}, nil
	case "cursor":
		b := substitute(body, cursorSubstitutions())
		desc := substitute(fm.Description, cursorSubstitutions())
		skillFile := "---\nname: " + fm.Name + "\ndescription: " + desc + "\n---\n\n" + b
		return []Rendered{
			{Path: "skills/mesh/SKILL.md", Body: []byte(skillFile)},
			{Path: "commands/mesh.md", Body: []byte(b)},
		}, nil
	default:
		return nil, fmt.Errorf("mcpinstall: render: unknown client %q", client)
	}
}

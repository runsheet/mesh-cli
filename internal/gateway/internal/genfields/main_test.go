package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func setup(t *testing.T, list string) (schema, fields, out string) {
	t.Helper()
	dir := t.TempDir()
	schema = filepath.Join(dir, "schema.json")
	s := renderSchema(Schema{Types: []Type{{Name: "NodeIndex", Kind: "OBJECT", Fields: []Field{
		{Name: "desiredVersion", Type: "String"}, {Name: "id", Type: "ID!"}, {Name: "name", Type: "String!"},
	}}}})
	if err := os.WriteFile(schema, s, 0o644); err != nil {
		t.Fatal(err)
	}
	fields = filepath.Join(dir, "fields")
	if err := os.Mkdir(fields, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(fields, "NodeIndex.txt"), []byte(list), 0o644); err != nil {
		t.Fatal(err)
	}
	return schema, fields, filepath.Join(dir, "fields_gen.go")
}

func TestGenerateListsRequiredAndOptional(t *testing.T) {
	schema, fields, out := setup(t, "# comment\ndesiredVersion?\nid\nname\n")
	if err := generate(schema, fields, out); err != nil {
		t.Fatal(err)
	}
	got, _ := os.ReadFile(out)
	for _, want := range []string{
		"// Code generated by internal/genfields from schema.json and fields/*.txt. DO NOT EDIT.",
		"var nodeRequired = []string{\n\t\"id\",\n\t\"name\",\n}",
		"var nodeOptional = []string{\n\t\"desiredVersion\",\n}",
		`var nodeFields = strings.Join(nodeRequired, " ")`,
		`var nodeOptionalFields = strings.Join(nodeOptional, " ")`,
	} {
		if !strings.Contains(string(got), want) {
			t.Errorf("fields_gen.go lacks %q:\n%s", want, got)
		}
	}
}

func TestGenerateRefusesAFieldNotInTheSchema(t *testing.T) {
	schema, fields, out := setup(t, "id\nname\nnoSuchField\n")
	err := generate(schema, fields, out)
	if err == nil || !strings.Contains(err.Error(), "NodeIndex.noSuchField") {
		t.Fatalf("err = %v, want one naming NodeIndex.noSuchField", err)
	}
}

func TestGenerateRefusesAnUnsortedList(t *testing.T) {
	schema, fields, out := setup(t, "name\nid\n")
	if err := generate(schema, fields, out); err == nil || !strings.Contains(err.Error(), "out of order") {
		t.Fatalf("err = %v, want out of order", err)
	}
}
